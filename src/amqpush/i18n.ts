export type AmqpKey = keyof typeof en

const DICTIONARIES: Record<string, Record<AmqpKey, string>> = { en, ru }

export type AmqpTranslate = (key: AmqpKey, values?: Record<string, string | number>) => string

/** Перевод внутри раздела. Язык берётся у приложения — он один на окно. */
export function useAmqpText(): AmqpTranslate {
  const { language } = useI18n()
  const dictionary = DICTIONARIES[language] ?? en
  return (key, values) => {
    const template = dictionary[key] ?? en[key] ?? key
    if (!values) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in values ? String(values[name]) : match,
    )
  }
}
